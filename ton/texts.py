# -*- coding: utf-8 -*-
"""Переписывает тексты с языка «как устроен сайт» на язык клиентки."""
import io

p = 'index.html'
s = io.open(p, encoding='utf-8').read()

ЗАМЕНЫ = [
    # ---------- расписание ----------
    ("""          <p>
            Это не картинка расписания. Свободное время считается с учётом
            того, сколько идёт услуга и что уже занято у колориста.
          </p>""",
     """          <p>
            Выберите услугу и день. Покажем время, на которое реально можно
            прийти, и во сколько вы освободитесь — блондирование занимает
            целый день, и знать об этом лучше заранее.
          </p>"""),

    # ---------- до и после ----------
    ("""          <p>
            Один и тот же клиент, одно освещение, один ракурс. Потяните
            полосу в сторону — увидите, с чего начинали.
          </p>""",
     """          <p>
            Потяните полосу в сторону. Слева — как пришли, справа — как ушли.
          </p>"""),

    # ---------- отзывы ----------
    ("""          <p>
            Через сутки после визита бот сам просит оценить работу. Публикуем
            всё подряд, включая тройки — иначе в отзывах нет смысла.
          </p>""",
     """          <p>
            На следующий день после визита спрашиваем, как получилось.
            Показываем все ответы — и хорошие, и не очень.
          </p>"""),

    # ---------- вопросы ----------
    ("""          <p>
            Здесь то, из-за чего откладывают запись. Отвечаем как есть,
            включая неприятное.
          </p>""",
     """          <p>
            Если вы всё ещё сомневаетесь — скорее всего, вот из-за чего.
          </p>"""),

    # ---------- напоминание: «в боте» ----------
    ("""              <p>
                Мы сами напишем в боте за неделю до того, как пора обновлять —
                следить за календарём не нужно.
              </p>""",
     """              <p>
                Напомним сами за неделю до того, как пора обновлять —
                следить за календарём не нужно.
              </p>"""),

    # ---------- подпись под кнопкой ----------
    ("""              <i>●</i> Свободное время видно сразу — спрашивать и ждать ответа не нужно""",
     """              <i>●</i> Свободное время видно сразу — звонить и ждать ответа не нужно"""),

    # ---------- подвал ----------
    ("""            <p>Свободные окошки видно сразу, ждать ответа администратора не нужно.</p>""",
     """            <p>Видно, что свободно на ближайшие дни. Перезванивать вам никто не будет.</p>"""),
]

for было, стало in ЗАМЕНЫ:
    assert было in s, 'не нашёл: ' + было.strip()[:60]
    s = s.replace(было, стало, 1)

# ---------- строка состояния над расписанием ----------
# Была: «Время посчитано по расписанию салона · бот пока не отдаёт данные сайту»
БЫЛО_ЖИВОСТЬ = """          .catch(function () {
            liveText.textContent =
              'Время посчитано по расписанию салона · бот пока не отдаёт данные сайту'
            live.setAttribute('data-state', 'snapshot')
          })"""
СТАЛО_ЖИВОСТЬ = """          .catch(function () {
            // Клиентке незачем знать, откуда взялось расписание —
            // ей важно, за какой срок оно показано
            liveText.textContent = 'Расписание на ближайшие пять дней'
            live.setAttribute('data-state', 'snapshot')
          })"""
assert БЫЛО_ЖИВОСТЬ in s
s = s.replace(БЫЛО_ЖИВОСТЬ, СТАЛО_ЖИВОСТЬ, 1)

БЫЛО_ЖИВОЕ = """            liveText.textContent = 'Расписание получено из бота вживую'
            live.setAttribute('data-state', 'live')"""
СТАЛО_ЖИВОЕ = """            liveText.textContent = 'Расписание обновляется прямо сейчас'
            live.setAttribute('data-state', 'live')"""
assert БЫЛО_ЖИВОЕ in s
s = s.replace(БЫЛО_ЖИВОЕ, СТАЛО_ЖИВОЕ, 1)

s = s.replace('<span id="liveText">Проверяю расписание…</span>',
              '<span id="liveText">Смотрим, что свободно…</span>', 1)

io.open(p, 'w', encoding='utf-8').write(s)
print('тексты переписаны под клиента')
